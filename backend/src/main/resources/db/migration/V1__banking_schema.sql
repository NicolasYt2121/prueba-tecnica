CREATE SEQUENCE account_number_seq MINVALUE 1 MAXVALUE 99999999 NO CYCLE;

CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identification_type VARCHAR(20) NOT NULL CHECK (identification_type IN ('CC','CE','PASAPORTE')),
 identification_number VARCHAR(25) NOT NULL CHECK (identification_number ~ '^[A-Za-z0-9-]{4,25}$'),
 first_name VARCHAR(80) NOT NULL CHECK (length(trim(first_name)) >= 2),
 last_name VARCHAR(80) NOT NULL CHECK (length(trim(last_name)) >= 2),
 email VARCHAR(160) NOT NULL CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
 birth_date DATE NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uq_customer_identity UNIQUE (identification_type, identification_number)
);
-- The trigger also protects inserts/updates performed directly using SQL.
CREATE FUNCTION require_adult() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.birth_date > ((CURRENT_TIMESTAMP AT TIME ZONE 'America/Bogota')::date - INTERVAL '18 years')::date THEN
  RAISE EXCEPTION 'El cliente debe ser mayor de edad' USING ERRCODE = '23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER customer_adult BEFORE INSERT OR UPDATE ON customers FOR EACH ROW EXECUTE FUNCTION require_adult();

CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
 type VARCHAR(20) NOT NULL CHECK (type IN ('AHORROS','CORRIENTE')),
 number VARCHAR(10) NOT NULL UNIQUE CHECK (number ~ '^[0-9]{10}$'),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVA' CHECK (status IN ('ACTIVA','INACTIVA','CANCELADA')),
 balance NUMERIC(19,2) NOT NULL DEFAULT 0,
 available_balance NUMERIC(19,2) NOT NULL DEFAULT 0,
 gmf_exempt BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 version BIGINT NOT NULL DEFAULT 0,
 CHECK ((type='AHORROS' AND left(number,2)='53') OR (type='CORRIENTE' AND left(number,2)='33')),
 CHECK (type <> 'AHORROS' OR balance >= 0),
 CHECK (status <> 'CANCELADA' OR balance = 0),
 CHECK (available_balance = balance)
);
CREATE INDEX idx_accounts_customer ON accounts(customer_id);

CREATE TABLE financial_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id UUID NOT NULL UNIQUE,
 type VARCHAR(20) NOT NULL CHECK (type IN ('CONSIGNACION','RETIRO','TRANSFERENCIA')),
 source_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT,
 destination_account_id BIGINT REFERENCES accounts(id) ON DELETE RESTRICT,
 amount NUMERIC(19,2) NOT NULL CHECK (amount > 0), description VARCHAR(250) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 reversed BOOLEAN NOT NULL DEFAULT false, reversed_at TIMESTAMPTZ,
 version BIGINT NOT NULL DEFAULT 0,
 CHECK ((type='CONSIGNACION' AND source_account_id IS NULL AND destination_account_id IS NOT NULL)
 OR (type='RETIRO' AND source_account_id IS NOT NULL AND destination_account_id IS NULL)
 OR (type='TRANSFERENCIA' AND source_account_id IS NOT NULL AND destination_account_id IS NOT NULL AND source_account_id<>destination_account_id)),
 CHECK (reversed = (reversed_at IS NOT NULL))
);
CREATE TABLE movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 transaction_id BIGINT NOT NULL REFERENCES financial_transactions(id) ON DELETE RESTRICT,
 account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
 delta NUMERIC(19,2) NOT NULL CHECK (delta <> 0), balance_after NUMERIC(19,2) NOT NULL,
 reversal BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(transaction_id,account_id,reversal)
);
CREATE INDEX idx_movements_account ON movements(account_id,id);

CREATE FUNCTION audit_timestamp() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP = 'INSERT' THEN NEW.created_at=clock_timestamp(); ELSE NEW.created_at=OLD.created_at; END IF;
 NEW.updated_at=clock_timestamp();
 RETURN NEW;
END $$;
CREATE TRIGGER customer_timestamp BEFORE INSERT OR UPDATE ON customers FOR EACH ROW EXECUTE FUNCTION audit_timestamp();
CREATE TRIGGER account_timestamp BEFORE INSERT OR UPDATE ON accounts FOR EACH ROW EXECUTE FUNCTION audit_timestamp();
CREATE TRIGGER transaction_timestamp BEFORE INSERT OR UPDATE ON financial_transactions FOR EACH ROW EXECUTE FUNCTION audit_timestamp();
